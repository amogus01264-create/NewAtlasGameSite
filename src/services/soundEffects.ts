      osc.frequency.setValueAtTime(523.25, now + 0.08); // C5
      osc.frequency.setValueAtTime(659.25, now + 0.16); // E5
      osc.frequency.setValueAtTime(783.99, now + 0.24); // G5

      gain.gain.setValueAtTime(0.12, now);
